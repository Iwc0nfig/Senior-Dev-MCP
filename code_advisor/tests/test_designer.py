"""Designer-partial synthesis.

Invariants only -- no frozen page counts. The question each test answers is
"would the graph mislead an agent?", not "how many pages were there in
September".
"""

from __future__ import annotations

import re


from senior_dev_code.index import designer as dz
from senior_dev_code.index import markup as mk


def _pages(ctx, like: str):
    return ctx.con.execute(
        "SELECT p.*, f.rel_path FROM pages p JOIN files f "
        "ON f.file_id = p.markup_file WHERE f.rel_path LIKE ?",
        (like,),
    ).fetchall()


def test_every_app_page_gets_a_synthesised_partial(ctx):
    """The name is the invariant: *every*.

    A Website Project page with no synthesised partial has 0 resolvable control
    identifiers, so every reference through that page's UI layer is wrong. One
    missing page is a correctness bug; the absolute number of pages is not.
    """
    rows = _pages(ctx, "Legacy/App/%")
    assert rows, "no App/ pages in the index -- run scripts/reindex.py"
    missing = [r["rel_path"] for r in rows if not r["synth_path"]]
    assert not missing, (
        f"{len(missing)} of {len(rows)} App/ pages have no synthesised partial: "
        f"{missing[:5]}"
    )


def test_synthesised_files_exist_and_are_outside_the_workspace(ctx, cfg):
    from pathlib import Path

    rows = _pages(ctx, "Legacy/App/%")
    for r in rows[:40]:
        p = Path(cfg.synth_abs(r["synth_path"]))
        assert p.is_file(), f"missing {p}"
        assert cfg.paths.index_dir in p.parents, f"{p} is outside .index/"
        assert cfg.paths.workspaces not in p.parents


def test_emitted_fields_are_protected_global_and_typed(ctx, cfg):
    from pathlib import Path

    rows = _pages(ctx, "Legacy/App/%")
    field_rx = re.compile(r"^\s*protected global::([\w.]+) @?\w+;$")
    checked = 0
    for r in rows[:60]:
        text = Path(cfg.synth_abs(r["synth_path"])).read_text(encoding="utf-8")
        assert text.startswith("// <auto-generated>")
        for line in text.splitlines():
            if "protected global::" in line:
                m = field_rx.match(line)
                assert m, f"malformed field: {line!r}"
                t = m.group(1)
                # Either a namespaced FQN, or a bare global-namespace class --
                # a user control's Inherits in a Website Project has no
                # namespace (e.g. `system_controls_exnavbar`).
                assert re.fullmatch(r"[A-Za-z_]\w*(\.\w+)*", t), t
                checked += 1
    assert checked > 0


def test_no_namespace_unless_the_codebehind_declares_one(ctx, cfg):
    """A namespace the code-behind does not declare puts the synthesised field
    in a different type than the one ASP.NET would generate -- the field then
    silently fails to bind."""
    from pathlib import Path

    rows = _pages(ctx, "Legacy/App/%")
    for r in rows:
        text = Path(cfg.synth_abs(r["synth_path"])).read_text(encoding="utf-8")
        if not re.search(r"^namespace ", text, re.MULTILINE):
            continue
        cb = ctx.con.execute(
            "SELECT container FROM symbols WHERE file_id=? AND kind='class' AND name=?",
            (r["codebehind_file"], r["inherits"]),
        ).fetchone()
        assert cb and cb["container"], (
            f"{r['rel_path']} emitted a namespace but its code-behind has none"
        )


def test_controls_without_an_id_get_no_field(ctx, markup_ctx, cfg):
    """ASP.NET emits no field for a control with no ID; emitting one would be a
    fabrication."""
    from pathlib import Path

    rows = _pages(ctx, "Legacy/App/%")
    seen_no_id = 0
    for row in rows[:80]:
        src_path = Path(cfg.abs_of(row["rel_path"]))
        ex = mk.scan(src_path.read_bytes(), src_path, markup_ctx)
        seen_no_id += sum(1 for c in ex.controls if not c.ctl_id)
        text = Path(cfg.synth_abs(row["synth_path"])).read_text(encoding="utf-8")
        fields = set(re.findall(r"protected global::[\w.]+ @?(\w+);", text))
        ids = {c.ctl_id for c in ex.controls if c.ctl_id}
        # Never a field for something with no ID, and never an invented name.
        assert fields <= ids, f"{row['rel_path']}: {sorted(fields - ids)}"
    assert seen_no_id > 0, "expected some controls without an ID across App/"


def test_cs0102_guard_is_exercised(ctx):
    """The guard must be running against real data even though this codebase
    happens to have zero collisions.

    A collision means the synthesised partial redeclares a member the
    code-behind already has -- the page then does not compile and every Roslyn
    answer through it is missing.
    """
    rows = ctx.con.execute(
        "SELECT p.inherits, p.codebehind_file, p.markup_file FROM pages p "
        "WHERE p.codebehind_file IS NOT NULL AND p.is_wap=0 AND p.inherits IS NOT NULL"
    ).fetchall()
    assert rows, "no Website Project pages to check"
    total_members = 0
    collisions: list[str] = []
    for r in rows:
        members = {
            x[0]
            for x in ctx.con.execute(
                "SELECT name FROM symbols WHERE file_id=? AND container=? "
                "AND kind IN ('method','property','field','event')",
                (r["codebehind_file"], r["inherits"]),
            )
        }
        total_members += len(members)
        ids = {
            x[0]
            for x in ctx.con.execute(
                "SELECT DISTINCT ctl_id FROM controls WHERE markup_file=? "
                "AND ctl_id IS NOT NULL",
                (r["markup_file"],),
            )
        }
        collisions.extend(f"{r['inherits']}.{n}" for n in members & ids)

    assert total_members > 0, "guard would be vacuous with no members to compare"
    assert not collisions, f"CS0102 collisions: {collisions[:5]}"


def test_web_application_projects_are_left_alone(ctx):
    """A page with a real *.designer.cs must not be synthesised."""
    waps = ctx.con.execute(
        "SELECT p.*, f.rel_path FROM pages p JOIN files f ON f.file_id=p.markup_file "
        "WHERE p.is_wap=1"
    ).fetchall()
    assert waps, "expected at least one Web Application Project page"
    for r in waps:
        assert r["synth_path"] is None
        assert r["designer_file"]


def test_master_type_is_resolved_to_a_class_not_a_path(ctx):
    rows = ctx.con.execute(
        "SELECT master_type FROM pages WHERE master_type IS NOT NULL"
    ).fetchall()
    assert rows
    for r in rows:
        assert "/" not in r["master_type"], r["master_type"]
        assert not r["master_type"].startswith("~")


def test_synth_path_is_stable_for_a_given_page(cfg):
    a = dz.synth_path(cfg.paths.index_dir, "Legacy/App/x/y.aspx", "ui_x_y")
    b = dz.synth_path(cfg.paths.index_dir, "Legacy/App/x/y.aspx", "ui_x_y")
    c = dz.synth_path(cfg.paths.index_dir, "Legacy/App/x/z.aspx", "ui_x_z")
    assert a == b
    assert a != c


def test_keyword_ids_are_escaped():
    page = mk.PageInfo(directive="page", inherits="ui_test")
    ctl = mk.ControlInfo(
        control_ref="asp:TextBox", tag_prefix="asp", tag_name="TextBox",
        ctl_id="event", resolved_type="System.Web.UI.WebControls.TextBox",
        resolution="bcl_webcontrols", line=3, col=1, byte_start=0,
    )
    from pathlib import Path

    res = dz.emit(page, "x.aspx", [ctl], set(), index_dir=Path("."))
    assert "@event;" in res.text